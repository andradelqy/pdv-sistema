create or replace function public.registrar_ponto(
  p_funcionario_id uuid,
  p_pin text,
  p_tipo text,
  p_latitude numeric,
  p_longitude numeric
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_usuario uuid := auth.uid();
  v_loja text;
  v_papel text;
  v_pin_hash text;
begin
  select loja_id, role into v_loja, v_papel
  from public.perfis where id = v_usuario and status = 'ativo';
  if v_loja is null or v_papel not in ('owner', 'gerente') then
    raise exception 'Usuário sem permissão para registrar ponto';
  end if;
  if not (select private.assinatura_atual_ativa()) then
    raise exception 'Assinatura da loja indisponível';
  end if;
  if p_tipo not in ('entrada', 'saida') then
    raise exception 'Tipo de ponto inválido';
  end if;
  if p_latitude not between -90 and 90 or p_longitude not between -180 and 180 then
    raise exception 'Localização inválida';
  end if;

  select pin_hash into v_pin_hash
  from public.perfis
  where id = p_funcionario_id and loja_id = v_loja and status = 'ativo';
  if v_pin_hash is null or extensions.crypt(p_pin, v_pin_hash) <> v_pin_hash then
    raise exception 'PIN incorreto';
  end if;

  insert into public.ponto_eletronico (
    loja_id, usuario_id, registrado_por, tipo, latitude, longitude
  ) values (
    v_loja, p_funcionario_id, v_usuario, p_tipo, p_latitude, p_longitude
  );
  return jsonb_build_object('ok', true, 'tipo', p_tipo);
end;
$$;
revoke all on function public.registrar_ponto(uuid, text, text, numeric, numeric) from public, anon;
grant execute on function public.registrar_ponto(uuid, text, text, numeric, numeric) to authenticated;

create or replace function public.definir_pin_ponto(
  p_funcionario_id uuid,
  p_novo_pin text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_usuario uuid := auth.uid();
  v_loja text;
  v_papel text;
begin
  select loja_id, role into v_loja, v_papel
  from public.perfis where id = v_usuario and status = 'ativo';
  if v_loja is null or v_papel not in ('owner', 'gerente') then
    raise exception 'Usuário sem permissão para definir PIN';
  end if;
  if not (select private.assinatura_atual_ativa()) then
    raise exception 'Assinatura da loja indisponível';
  end if;
  if p_novo_pin !~ '^[0-9]{4,8}$' then
    raise exception 'O PIN deve conter entre 4 e 8 números';
  end if;

  update public.perfis
  set pin_hash = extensions.crypt(p_novo_pin, extensions.gen_salt('bf')),
      updated_at = now()
  where id = p_funcionario_id and loja_id = v_loja and status = 'ativo';
  if not found then
    raise exception 'Colaborador não encontrado';
  end if;

  insert into public.auditoria_operacional (
    loja_id, usuario_id, acao, entidade, entidade_id, payload
  ) values (v_loja, v_usuario, 'alterou_pin', 'perfil', p_funcionario_id::text, '{}'::jsonb);
end;
$$;
revoke all on function public.definir_pin_ponto(uuid, text) from public, anon;
grant execute on function public.definir_pin_ponto(uuid, text) to authenticated;

-- Reduz a exposição do perfil: PIN e seu hash nunca são retornados pela API.
revoke select on public.perfis from authenticated;
grant select (id, email, nome, role, status, loja_id, updated_at) on public.perfis to authenticated;

commit;
