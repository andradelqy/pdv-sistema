begin;

-- Hardening incremental e não destrutivo para instalações existentes.
-- Mantém a Data API fechada para visitantes e declara os privilégios usados
-- pelo cliente autenticado de forma explícita.
revoke all on all tables in schema public from anon;
revoke all on all sequences in schema public from anon;
grant usage on schema public to authenticated;

-- Privilégios explícitos: não dependem mais do default legado do Supabase.
-- As policies continuam decidindo quais linhas e papéis podem operar.
grant select, insert, update, delete on
  public.produtos, public.movimentacoes, public.clientes, public.vendas,
  public.itens_venda, public.caixas, public.pedidos_compra,
  public.itens_pedido_compra
to authenticated;
grant select, insert on public.caixa_entradas to authenticated;
grant select, insert, update on public.entregas, public.rastreio_entregadores to authenticated;
grant select, insert on public.rastreio_pontos, public.historico_precos_compra to authenticated;
grant select, insert, update on public.inventarios, public.itens_inventario to authenticated;
grant select on public.assinaturas_lojas, public.auditoria_operacional to authenticated;

do $$
declare sequencia text;
begin
  foreach sequencia in array array[
    'itens_venda_id_seq', 'caixa_entradas_id_seq',
    'itens_pedido_compra_id_seq', 'rastreio_pontos_id_seq',
    'historico_precos_compra_id_seq', 'auditoria_operacional_id_seq'
  ] loop
    if to_regclass('public.' || sequencia) is not null then
      execute format('grant usage, select on sequence public.%I to authenticated', sequencia);
    end if;
  end loop;
end
$$;

-- Telemetria operacional sem payloads pessoais/sigilosos. O navegador apenas
-- insere eventos da própria loja; somente owner/gerente podem consultá-los.
create table if not exists public.erros_aplicacao (
  id bigint generated by default as identity primary key,
  loja_id text not null,
  usuario_id uuid references auth.users(id) on delete set null,
  fingerprint text not null,
  origem text not null check (char_length(origem) between 1 and 120),
  mensagem text not null check (char_length(mensagem) between 1 and 1000),
  contexto jsonb not null default '{}'::jsonb,
  versao text not null default '2.0.0',
  criado_em timestamptz not null default now()
);
create index if not exists erros_aplicacao_loja_criado_idx
  on public.erros_aplicacao (loja_id, criado_em desc);
create index if not exists erros_aplicacao_fingerprint_idx
  on public.erros_aplicacao (loja_id, fingerprint, criado_em desc);

alter table public.erros_aplicacao enable row level security;
revoke all on public.erros_aplicacao from public, anon, authenticated;
grant insert, select on public.erros_aplicacao to authenticated;
grant usage, select on sequence public.erros_aplicacao_id_seq to authenticated;

drop policy if exists "registrar erro da propria loja" on public.erros_aplicacao;
create policy "registrar erro da propria loja"
on public.erros_aplicacao for insert to authenticated
with check (
  usuario_id = (select auth.uid())
  and loja_id = (select private.loja_atual())
);

drop policy if exists "gestao consulta erros da loja" on public.erros_aplicacao;
create policy "gestao consulta erros da loja"
on public.erros_aplicacao for select to authenticated
using (
  loja_id = (select private.loja_atual())
  and (select private.papel_atual()) in ('owner', 'gerente')
);

-- Garante que módulos criados depois do controle de assinatura também sejam
-- bloqueados quando a loja estiver suspensa. Credenciais e telemetria ficam de
-- fora: credenciais são service_role-only e erros precisam continuar chegando.
do $$
declare tabela record;
begin
  for tabela in
    select c.table_name
    from information_schema.columns c
    join information_schema.tables t
      on t.table_schema = c.table_schema and t.table_name = c.table_name
    where c.table_schema = 'public'
      and c.column_name = 'loja_id'
      and t.table_type = 'BASE TABLE'
      and c.table_name not in (
        'perfis', 'assinaturas_lojas', 'whatsapp_credenciais', 'erros_aplicacao'
      )
  loop
    execute format('alter table public.%I enable row level security', tabela.table_name);
    execute format('drop policy if exists "assinatura ativa da loja" on public.%I', tabela.table_name);
    execute format(
      'create policy "assinatura ativa da loja" on public.%I as restrictive for all to authenticated
       using (loja_id = (select private.loja_atual()) and (select private.assinatura_atual_ativa()))
       with check (loja_id = (select private.loja_atual()) and (select private.assinatura_atual_ativa()))',
      tabela.table_name
    );
  end loop;
end
$$;

