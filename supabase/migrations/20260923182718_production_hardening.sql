-- Ao criar o primeiro owner de uma loja, a assinatura de avaliação passa a ser
-- provisionada automaticamente. Outros colaboradores reutilizam a mesma linha.
create or replace function private.provisionar_assinatura_nova_loja()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.role = 'owner' and new.loja_id is not null and btrim(new.loja_id) <> '' then
    insert into public.assinaturas_lojas (
      loja_id, nome_loja, plano, status, periodo_teste_ate
    ) values (
      new.loja_id, new.loja_id, 'teste', 'trial', now() + interval '7 days'
    ) on conflict (loja_id) do nothing;
  end if;
  return new;
end;
$$;
revoke all on function private.provisionar_assinatura_nova_loja() from public, anon, authenticated;

drop trigger if exists perfis_provisionar_assinatura on public.perfis;
create trigger perfis_provisionar_assinatura
after insert or update of loja_id, role on public.perfis
for each row execute function private.provisionar_assinatura_nova_loja();

-- Recebimento de compra transacional e idempotente. Pedido, estoque,
-- movimentação, histórico de custo e auditoria são confirmados juntos.
create or replace function public.receber_pedido_compra_atomico(p_pedido_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_usuario uuid := auth.uid();
  v_loja text;
  v_papel text;
  v_status text;
  v_recebido_em timestamptz;
  v_item record;
begin
  if v_usuario is null then
    raise exception 'Sessão inválida';
  end if;

  select loja_id, role into v_loja, v_papel
  from public.perfis
  where id = v_usuario and status = 'ativo';

  if v_loja is null or v_papel not in ('owner', 'gerente') then
    raise exception 'Usuário sem permissão para receber compras';
  end if;
  if not (select private.assinatura_atual_ativa()) then
    raise exception 'Assinatura da loja indisponível';
  end if;

  select status, recebido_em into v_status, v_recebido_em
  from public.pedidos_compra
  where id = p_pedido_id and loja_id = v_loja
  for update;

  if not found then
    raise exception 'Pedido de compra não encontrado';
  end if;
  if v_status = 'received' then
    return jsonb_build_object('ok', true, 'duplicado', true, 'pedido_id', p_pedido_id);
  end if;
  if v_status not in ('pending', 'in_transit') then
    raise exception 'Somente pedidos aprovados ou em trânsito podem ser recebidos';
  end if;
  if not exists (
    select 1 from public.itens_pedido_compra
    where pedido_id = p_pedido_id and loja_id = v_loja
  ) then
    raise exception 'Pedido sem itens';
  end if;

  -- Ordem estável de bloqueio reduz a possibilidade de deadlock quando dois
  -- recebimentos incluem o mesmo produto.
  perform produto.id
  from public.produtos produto
  join public.itens_pedido_compra item
    on item.produto_id = produto.id and item.loja_id = produto.loja_id
  where item.pedido_id = p_pedido_id and produto.loja_id = v_loja
  order by produto.id
  for update of produto;

  if exists (
    select 1
    from public.itens_pedido_compra item
    left join public.produtos produto
      on produto.id = item.produto_id and produto.loja_id = item.loja_id
    where item.pedido_id = p_pedido_id
      and item.loja_id = v_loja
      and produto.id is null
  ) then
    raise exception 'Pedido contém produto inexistente';
  end if;

  for v_item in
    select item.produto_id, item.quantidade_solicitada, item.preco_unit_custo,
           produto.fornecedor
    from public.itens_pedido_compra item
    join public.produtos produto
      on produto.id = item.produto_id and produto.loja_id = item.loja_id
    where item.pedido_id = p_pedido_id and item.loja_id = v_loja
    order by item.produto_id
  loop
    update public.produtos
    set estoque = estoque + v_item.quantidade_solicitada,
        preco_compra = case
          when v_item.preco_unit_custo > 0 then v_item.preco_unit_custo
          else preco_compra
        end,
        updated_at = now()
    where id = v_item.produto_id and loja_id = v_loja;

    insert into public.movimentacoes (
      id, user_id, loja_id, produto_id, tipo, quantidade, data, motivo,
      aprovado_por, aprovado_em, obs
    ) values (
      'compra_' || p_pedido_id::text || '_' || v_item.produto_id,
      v_usuario, v_loja, v_item.produto_id, 'entrada',
      v_item.quantidade_solicitada, current_date, 'compra',
      v_usuario, now(), 'Recebimento do pedido ' || p_pedido_id::text
    ) on conflict (id) do nothing;

    if v_item.preco_unit_custo > 0 then
      insert into public.historico_precos_compra (
        loja_id, produto_id, pedido_id, fornecedor, preco_unitario
      ) values (
        v_loja, v_item.produto_id, p_pedido_id, v_item.fornecedor,
        v_item.preco_unit_custo
      );
    end if;
  end loop;

  update public.pedidos_compra
  set status = 'received', recebido_em = now()
  where id = p_pedido_id and loja_id = v_loja;

  insert into public.auditoria_operacional (
    loja_id, usuario_id, acao, entidade, entidade_id, payload
  ) values (
    v_loja, v_usuario, 'recebeu', 'pedido_compra', p_pedido_id::text,
    jsonb_build_object('status_anterior', v_status)
  );

  return jsonb_build_object('ok', true, 'duplicado', false, 'pedido_id', p_pedido_id);
end;
$$;
revoke all on function public.receber_pedido_compra_atomico(uuid) from public, anon;
grant execute on function public.receber_pedido_compra_atomico(uuid) to authenticated;

-- Ponto eletrônico: o PIN deixa de trafegar para o navegador e passa a ser
-- validado por hash dentro do banco.
create extension if not exists pgcrypto with schema extensions;
alter table public.perfis add column if not exists pin_hash text;

do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'perfis' and column_name = 'pin'
  ) then
    execute 'update public.perfis set pin_hash = extensions.crypt(pin::text, extensions.gen_salt(''bf'')) where pin is not null and pin_hash is null';
  end if;
end
$$;

